function ownerOf(dir) {
  for (const [prefix, wp] of OWNERS) {
    if (dir === prefix || dir.startsWith(prefix + "/")) return wp;
  }
  return null;
}

function directories() {
  const tracked = execFileSync("git", ["ls-files"], {
    cwd: ROOT,
    encoding: "utf8",
  })
    .split("\n")
    .filter(Boolean);
  const roots = [
    "packages/",
    "frontend/src/ts/",
    "frontend/src/styles/",
    "frontend/static/",
    "backend/src/",
  ];
  const dirs = new Set();
  for (const file of tracked) {
    if (!roots.some((r) => file.startsWith(r))) continue;
    const dir = posix.dirname(file);
    if (dir !== ".") dirs.add(dir);
  }
  return [...dirs].sort();
}

function ownershipReport() {
  const dirs = directories();
  const rows = [];
  let unowned = 0;
  for (const dir of dirs) {
    const wp = ownerOf(dir);
    if (wp === null) unowned++;
    rows.push(`| \`${dir}\` | ${wp ?? "**UNOWNED**"} |`);
  }
  return `# Directory-to-owner listing (DoD-51 / INV-206)

Generated by \`node scripts/requirement-coverage.mjs\`. Do not hand-edit — regenerate.

Every **tracked** directory under \`packages/\`, \`frontend/src/ts/\`, \`frontend/src/styles/\`,
\`frontend/static/\` and \`backend/src/\`, with the single work package that owns it under §6 / §6.2 of
\`docs/REQUIREMENTS.md\` (as amended by coordinator ruling **R1**). Ownership is resolved most-specific-first,
which is the §6 reading rule: \`frontend/src/ts/components/pages/account\` (WP-09) beats
\`frontend/src/ts/components/pages\` (WP-08) beats \`frontend/src/ts/components\` (WP-08).

**Directories: ${dirs.length}. Unowned: ${unowned}.**

| Directory | Owner |
|---|---|
${rows.join("\n")}
`;
}

