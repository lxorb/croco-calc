function read(path) {
  return readFileSync(join(ROOT, path), "utf8");
}

/** Every id of a document's own prefix that appears anywhere in that document. */
function collectIds() {
  const out = [];
  for (const [prefix, [path, area]] of Object.entries(DOCS)) {
    const src = read(path);
    const re = new RegExp(prefix + "(\\d{3}[a-z]?)", "g");
    const ids = new Set();
    for (const m of src.matchAll(re)) ids.add(prefix + m[1]);
    for (const id of [...ids].sort()) out.push({ id, prefix, area, path });
  }
  return out;
}

/** Ids §2.31 overrules or amends, so DoD-03 governs them rather than DoD-02. */
function collectRuled() {
  const master = read("docs/REQUIREMENTS.md");
  const start = master.indexOf("### 2.31 Complete list");
  const end = master.indexOf("### 2.32 Standing user decisions");
  const table = master.slice(start, end === -1 ? undefined : end);
  const ruled = new Set();
  for (const m of table.matchAll(/(ME|SB|CP|AC|INV|INF)-(\d{3}[a-z]?)/g)) {
    ruled.add(m[0].replace("ME-", "ME-"));
  }
  return ruled;
}

function citationsFor(id) {
  try {
    const out = execFileSync(
      "git",
      ["grep", "-l", "--fixed-strings", id, "--", ...SEARCH_ROOTS],
      { cwd: ROOT, encoding: "utf8" },
    );
    return out
      .split("\n")
      .filter(Boolean)
      .map((p) => posix.normalize(p));
  } catch {
    return [];
  }
}

function isTest(path) {
  return path.includes("__tests__") || path.includes(".spec.");
}

function coverageReport(ids, ruled) {
  const rows = [];
  let cited = 0;
  let tested = 0;
  let ruledCount = 0;

  for (const { id, area } of ids) {
    const files = citationsFor(id);
    const isRuled = ruled.has(id);
    if (isRuled) ruledCount++;
    if (files.length > 0) cited++;
    if (files.some(isTest)) tested++;

    const kind =
      files.length === 0 ? "none" : files.some(isTest) ? "test" : "code";
    const shown = files.slice(0, 3).join("<br>");
    const more = files.length > 3 ? `<br>…and ${files.length - 3} more` : "";
    rows.push(
      `| ${id} | ${area} | ${isRuled ? "§2.31" : "—"} | ${kind} | ${files.length} | ${shown}${more} |`,
    );
  }

  const head = `# Requirement coverage report (DoD-02)

Generated by \`node scripts/requirement-coverage.mjs\`. Do not hand-edit — regenerate.

**Rows: ${ids.length}.** The §1 index of \`docs/REQUIREMENTS.md\` headlines **1111**; the true figure is
**${ids.length}**, because revision 3 added the lettered \`INF-053a\` and \`INF-062a\` after that headline was
written. Every other per-document count matches the index exactly (ME 184, SB 165, CP 197, AC 187, INV 220);
only INF moved, 158 → 160.

**What a row means.** \`Evidence\` is the number of files under \`packages/\`, \`frontend/src\`,
\`frontend/__tests__\`, \`frontend/vite-plugins\`, \`backend/src\`, \`backend/__tests__\`, \`infra/\`,
\`docker/\`, \`scripts/\` and \`.github/\` that cite the id **literally**. \`docs/\` is excluded on purpose: a
requirement citing itself is not evidence of anything. \`Kind\` is \`test\` when at least one citation is in a
spec file, \`code\` when the citations are implementation only, and \`none\` when the id is nowhere in the tree.

**What a row does not mean.** A citation shows that code was written against the requirement, not that the
requirement is met. The behavioural proof is §7.4/§7.5 and the reviews. Equally, \`none\` is not automatically
a defect: ids overruled by §2.31 (marked \`§2.31\`, governed by DoD-03 instead), pure prose/assumption ids, and
disposition rows in doc 05 that record a **deletion** all legitimately leave no citation behind — the
deletion sweep DoD-04 is what proves those.

## Summary

| | Count |
|---|---|
| Indexed ids | ${ids.length} |
| Cited somewhere in the implementation | ${cited} |
| Cited by at least one test | ${tested} |
| No literal citation | ${ids.length - cited} |
| Listed in §2.31 (DoD-03 governs) | ${ruledCount} |

## Rows

| ID | Area | Ruled | Kind | Evidence | Files |
|---|---|---|---|---|---|
`;

  return head + rows.join("\n") + "\n";
}

