/**
 * DoD-02 / DoD-51 evidence generator.
 *
 *   node scripts/requirement-coverage.mjs
 *
 * Writes two files, both of which the Definition of Done asks for by name:
 *
 *   docs/coverage/requirement-coverage.md  — one row per indexed requirement id
 *                                            (DoD-02)
 *   docs/coverage/directory-ownership.md   — one row per source directory
 *                                            (DoD-51 / INV-206)
 *
 * The coverage report is **mechanically derived**, and says so in its own
 * header: for each id it greps the implementation tree for a literal citation
 * of that id and reports where it was found. A citation is evidence that some
 * code or test was written against the requirement; it is not a proof that the
 * requirement is satisfied — that is what §7's other 50 items are for. Rows with
 * no citation are listed as `none` so they are easy to find, which is the whole
 * point of the exercise.
 */
